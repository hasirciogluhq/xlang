// Plan 5.7: `--emit=header`, a C/C++ header for the `export(c)` surface.

#include "xlang/codegen/codegen.h"

#include <algorithm>
#include <format>
#include <set>
#include <sstream>

namespace xlang::codegen {

namespace {

[[nodiscard]] std::string cIdent(std::string name) {
    for (char& c : name) {
        if (!(std::isalnum(static_cast<unsigned char>(c)) != 0 || c == '_')) {
            c = '_';
        }
    }
    return name;
}

[[nodiscard]] std::string baseName(const Type& t) {
    switch (t.kind) {
    case TypeKind::Void: return "void";
    case TypeKind::Bool: return "bool";
    case TypeKind::Int: {
        if (t.bits == 0) {
            return t.is_signed ? "intptr_t" : "uintptr_t";
        }
        return std::format("{}int{}_t", t.is_signed ? "" : "u", t.bits);
    }
    case TypeKind::Float: return t.bits == 32 ? "float" : "double";
    case TypeKind::Enum:
        return t.path.empty() ? "int32_t" : cIdent(t.path.front());
    case TypeKind::Struct:
    case TypeKind::Class: return "struct " + cIdent(t.path.front());
    default: return "void";
    }
}

/// C declarator for `name` of type `t` (pointers, arrays and function pointers nest correctly).
[[nodiscard]] std::string declarator(const Type& t, const std::string& name) {
    switch (t.kind) {
    case TypeKind::Pointer: {
        const Type& e = *t.elem;
        if (e.kind == TypeKind::Array || e.kind == TypeKind::FnPtr) {
            return declarator(e, "(*" + name + ")");
        }
        return declarator(e, "*" + name);
    }
    case TypeKind::Array: {
        std::uint64_t n = 0;
        if (t.length != nullptr) {
            n = t.length->int_value;
        }
        return declarator(*t.elem, std::format("{}[{}]", name, n));
    }
    case TypeKind::FnPtr: {
        std::string params;
        for (std::size_t i = 0; i < t.params.size(); ++i) {
            params += (i != 0 ? ", " : "") + declarator(t.params[i], "");
        }
        if (params.empty()) {
            params = "void";
        }
        return declarator(*t.ret, std::format("(*{})({})", name.empty() ? "" : name, params));
    }
    default: {
        std::string s = baseName(t);
        if (!name.empty()) {
            s += " " + name;
        }
        return s;
    }
    }
}

}  // namespace

std::string generateHeader(const hir::Module& module, const LayoutQuery& layout, const std::string& guard) {
    std::ostringstream o;
    o << "/* Generated by xlang. Do not edit. */\n"
      << "#ifndef " << guard << "\n#define " << guard << "\n\n"
      << "#include <stdbool.h>\n#include <stddef.h>\n#include <stdint.h>\n\n"
      << "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n";

    std::set<std::string> emitted;
    const std::function<void(const Type&)> need = [&](const Type& t) {
        if (t.kind == TypeKind::Pointer || t.kind == TypeKind::Array) {
            if (t.elem) {
                need(*t.elem);
            }
            return;
        }
        if (t.kind == TypeKind::FnPtr) {
            for (const Type& p : t.params) {
                need(p);
            }
            if (t.ret) {
                need(*t.ret);
            }
            return;
        }
        if (t.kind == TypeKind::Enum && !t.path.empty() && emitted.insert(t.path.front()).second) {
            for (const hir::Enum& e : module.enums) {
                if (e.name != t.path.front()) {
                    continue;
                }
                const std::string name = cIdent(e.name);
                o << "typedef " << baseName(e.underlying) << " " << name << ";\nenum {\n";
                for (const hir::EnumMemberValue& m : e.members) {
                    o << "    " << name << "_" << m.name << " = " << (m.text.empty() ? std::to_string(m.int_value) : m.text)
                      << ",\n";
                }
                o << "};\n\n";
            }
            return;
        }
        if ((t.kind == TypeKind::Struct || t.kind == TypeKind::Class) && !t.path.empty() &&
            emitted.insert(t.path.front()).second) {
            for (const hir::Aggregate& a : module.aggregates) {
                if (a.name != t.path.front()) {
                    continue;
                }
                for (const hir::Field& f : a.fields) {
                    need(f.type);
                }
                const std::string name = cIdent(a.name);
                if (a.opaque) {
                    o << "struct " << name << ";\n\n";
                    continue;
                }
                o << "struct " << name << " {\n";
                if (a.is_class && !a.vtable.empty()) {
                    o << "    void* vptr;\n";
                }
                for (const hir::Field& f : a.fields) {
                    o << "    " << declarator(f.type, f.name) << ";\n";
                }
                o << "};\n";
                if (const auto l = layout(t)) {
                    o << "_Static_assert(sizeof(struct " << name << ") == " << l->size << ", \"layout of " << name
                      << "\");\n";
                }
                o << "\n";
            }
        }
    };

    // Types used by the exported surface first (and every @repr(c) type).
    for (const hir::Aggregate& a : module.aggregates) {
        if (!a.repr_c) {
            continue;
        }
        Type t;
        t.kind = a.is_class ? TypeKind::Class : TypeKind::Struct;
        t.path = {a.name};
        need(t);
    }
    for (const hir::Global& g : module.globals) {
        if (g.export_c) {
            need(g.type);
        }
    }
    for (const hir::Function& f : module.functions) {
        if (!f.export_c) {
            continue;
        }
        need(f.ret);
        for (std::uint32_t i = 0; i < f.param_count; ++i) {
            need(f.locals[i].type);
        }
    }
    for (const hir::Global& g : module.globals) {
        if (g.export_c) {
            o << "extern " << declarator(g.type, g.symbol.empty() ? g.name : g.symbol) << ";\n";
        }
    }
    for (const hir::Function& f : module.functions) {
        if (!f.export_c) {
            continue;
        }
        std::string params;
        for (std::uint32_t i = 0; i < f.param_count; ++i) {
            params += (i != 0 ? ", " : "") + declarator(f.locals[i].type, f.locals[i].name);
        }
        if (params.empty()) {
            params = "void";
        }
        o << declarator(f.ret, f.symbol.empty() ? f.name : f.symbol) << "(" << params << ");\n";
    }
    o << "\n#ifdef __cplusplus\n}\n#endif\n\n#endif /* " << guard << " */\n";
    return o.str();
}

}  // namespace xlang::codegen
