#!/usr/bin/env bash
# Generate the Homebrew formula (xlang.rb) for a release and print it to stdout.
#
# Usage: scripts/release/formula.sh <version> [dist-dir]
#   version   release version without the leading "v" (e.g. 0.1.0)
#   dist-dir  directory holding the *.tar.gz.sha256 files (default: dist)
#
# Environment:
#   GITHUB_REPOSITORY  owner/repo of the release (default: hasirciogluhq/xlang)
set -euo pipefail

if [ "$#" -lt 1 ]; then
  echo "usage: $0 <version> [dist-dir]" >&2
  exit 2
fi

version="$1"
dist="${2:-dist}"
repo="${GITHUB_REPOSITORY:-hasirciogluhq/xlang}"
base="https://github.com/${repo}/releases/download/v${version}"

sha_for() {
  local target="$1"
  local file="$dist/xlang_${version}_${target}.tar.gz.sha256"
  if [ ! -f "$file" ]; then
    echo "error: missing checksum file: $file" >&2
    exit 1
  fi
  awk '{print $1}' "$file"
}

darwin_arm64="$(sha_for darwin_arm64)"
darwin_amd64="$(sha_for darwin_amd64)"
linux_arm64="$(sha_for linux_arm64)"
linux_amd64="$(sha_for linux_amd64)"

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/release/formula.sh in ${repo}. Do not edit by hand.
class Xlang < Formula
  desc "LLVM-based systems language compiler"
  homepage "https://github.com/${repo}"
  version "${version}"

  depends_on "libffi"
  depends_on "zstd"

  on_macos do
    if Hardware::CPU.arm?
      url "${base}/xlang_${version}_darwin_arm64.tar.gz"
      sha256 "${darwin_arm64}"
    end
    if Hardware::CPU.intel?
      url "${base}/xlang_${version}_darwin_amd64.tar.gz"
      sha256 "${darwin_amd64}"
    end
  end

  on_linux do
    # The compiler shells out to clang to link; macOS gets it from the
    # Command Line Tools, Linux from Homebrew's llvm.
    depends_on "llvm"
    depends_on "ncurses"
    depends_on "zlib"

    if Hardware::CPU.arm? && Hardware::CPU.is_64_bit?
      url "${base}/xlang_${version}_linux_arm64.tar.gz"
      sha256 "${linux_arm64}"
    end
    if Hardware::CPU.intel? && Hardware::CPU.is_64_bit?
      url "${base}/xlang_${version}_linux_amd64.tar.gz"
      sha256 "${linux_amd64}"
    end
  end

  def install
    bin.install "xlang"
  end

  test do
    system "#{bin}/xlang", "--help"
  end
end
EOF
